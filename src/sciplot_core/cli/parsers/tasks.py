"""Register complete local tasks and the optional MCP transport."""

from pathlib import Path
from typing import Any


def register_task_commands(subparsers: Any) -> None:
    parser = subparsers.add_parser("task", help="Run and resume complete local plotting tasks.")
    actions = parser.add_subparsers(dest="task_action", required=True)
    from sciplot_core.cli.parsers.common_edits import register_common_edit_command
    from sciplot_core.cli.task_paper import register_paper_commands

    register_common_edit_command(actions)
    register_paper_commands(actions)
    capabilities = actions.add_parser("capabilities", help="Read the small task capability index, or a requested schema.")
    capabilities.add_argument("--json", action="store_true")
    capabilities.add_argument("--section", choices=("request", "response", "operations", "table_region", "common_edit", "paper_request", "semantic_intent"))
    capabilities.add_argument("--name", help="One action, response field or operation from the capability index.")
    capabilities.add_argument("--expected-contract", help="Reject schemas from a different capability fingerprint.")
    capabilities.add_argument("--full", action="store_true", help="Read all task schemas with repeated definitions factored out.")
    context = actions.add_parser("edit-context", help="Read runtime, current edit targets and selected schemas together; read-only.")
    context.add_argument("target", type=Path)
    context.add_argument("--operation", action="append", required=True, help="Advertised operation name; repeat for a batch.")
    context.add_argument("--figure", help="Registered figure identity; otherwise use the target's figure or primary figure.")
    context.add_argument("--json", action="store_true")
    region = actions.add_parser("table-region", help="Read a source-bound original cell rectangle; read-only.")
    region.add_argument("target", type=Path)
    region.add_argument("--query", type=Path, required=True, metavar="JSON_FILE", help="Path to a JSON query file; inline JSON is not a path. MCP accepts the query object directly.")
    region.add_argument("--json", action="store_true")
    find = actions.add_parser("find", help="Find recorded creation tasks by exact original source path; read-only.")
    find.add_argument("source", type=Path)
    find.add_argument("--tasks-root", type=Path, help="Task-history directory; default is SOURCE_PARENT/.sciplot/tasks.")
    find.add_argument("--limit", type=int, default=20)
    find.add_argument("--search-root", type=Path, action="append", help="Search saved work within this bounded folder; repeat for explicit scopes.")
    find.add_argument("--json", action="store_true")
    continuation = actions.add_parser("continue", help="Find a current editable original and return safe existing edit/recovery arguments; read-only.")
    continuation.add_argument("source", type=Path)
    continuation.add_argument("--search-root", type=Path, action="append")
    continuation.add_argument("--tasks-root", type=Path)
    continuation.add_argument("--target", type=Path, help="Explicit exact discovered target when copies or versions are ambiguous.")
    continuation.add_argument("--figure", help="Exact registered figure identity.")
    continuation.add_argument("--json", action="store_true")
    start = actions.add_parser("start", help="Execute a complete structured request locally.")
    start.add_argument("--request", type=Path, required=True, metavar="JSON_FILE", help="Path to the complete task JSON file; use task create flags for semantic attachment plotting.")
    start.add_argument("--task-dir", type=Path)
    start.add_argument("--json", action="store_true")
    start.add_argument("--full", action="store_true", help="Return the detailed task response; default is a compact receipt.")
    create = actions.add_parser("create", help="Start from original data without a request file; scientific questions remain explicit.")
    create.add_argument("source", type=Path, nargs="?", help="Original input; omit when using repeated --source attachments.")
    create.add_argument("--source", dest="sources", type=Path, action="append", help="Exact original table attachment; repeat to combine sources in this same task.")
    create.add_argument("--intent", type=Path, metavar="JSON_FILE", help="Optional small semantic intent JSON file, mutually exclusive with semantic flags; never a FigureTemplate.")
    create.add_argument("--x", help="Requested scientific X quantity, such as time or wavelength; independent of experiment identity.")
    create.add_argument("--x-header", help="Exact original header when several X candidates exist; source facts are not rewritten.")
    create.add_argument("--y-header", help="Exact original header when several response candidates exist; source facts are not rewritten.")
    create.add_argument("--x-unit", help="Requested X unit, such as min; program records a registered conversion from the original unit.")
    create.add_argument("--y", help="Requested left-axis scientific quantity, such as mass; a percentage unit alone does not declare mass.")
    create.add_argument("--y-unit", help="Requested left-axis unit; otherwise preserve the canonical original unit.")
    create.add_argument("--y-min", type=float, help="Explicit left-axis minimum in its displayed unit (for example 95 percent); does not clip or alter source data.")
    create.add_argument("--y-max", type=float, help="Explicit left-axis maximum in its displayed unit; omission fits actual observations with margin.")
    create.add_argument("--secondary-y", help="Requested right-axis scientific quantity, such as temperature.")
    create.add_argument("--secondary-y-unit", help="Requested right-axis unit; omission preserves the canonical original unit.")
    create.add_argument("--stages", choices=("concatenate", "source_order"), help="Explicit acquisition-stage intent; any unresolved order/boundary appears in one plan question.")
    create.add_argument("--stage-order", choices=("source_order", "temperature_continuity"), help="Explicit source order or source-evidenced temperature-continuity proposal; never drops a stage.")
    create.add_argument("--time-boundary", choices=("preserve_endpoint", "next_sample"), help="Keep both stage boundary points at equal time, or advance by the entering stage measured positive sample interval.")
    create.add_argument("--temperature-header", help="Exact original temperature role, such as Ts or Tr; never chosen by numeric equality.")
    create.add_argument("--temperature-source", type=int, help="Zero-based attachment index for the right-axis temperature; plan shows its exact file and SHA.")
    create.add_argument("--label", dest="labels", action="append", help="Authorized display label in attachment order; original scientific source/sample identities remain recorded.")
    create.add_argument("--marker-every", type=int, help="Display every Nth original point; line/scientific data keep all measurements.")
    create.add_argument("--interpolation", choices=("pchip",), help="Explicit shape-preserving display interpolation; original marker points remain unchanged.")
    create.add_argument("--interpolation-subdivisions", type=int, default=4, help="Display subdivisions per original interval (2–32); default 4, never additional measurements.")
    create.add_argument("--rule", dest="rule_id")
    create.add_argument("--template")
    create.add_argument("--profile", type=Path)
    create.add_argument("--choose-columns", action="store_true", help="Review original pair/sample groups in the same task before plotting.")
    create.add_argument("--xscale", choices=("log", "linear"), help="Explicit stress-relaxation time scale; keep source normalization and zero-time evidence.")
    create.add_argument("--out", type=Path)
    create.add_argument("--task-dir", type=Path)
    create.add_argument("--json", action="store_true")
    create.add_argument("--full", action="store_true", help="Return the detailed task response.")
    style = actions.add_parser("style", help="Preview an explicit ordinary sample color/width edit without request files.")
    style.add_argument("target", type=Path)
    samples = style.add_mutually_exclusive_group(required=True)
    samples.add_argument("--all-samples", action="store_true", help="Every exact unique ordinary sample in the selected figure.")
    samples.add_argument("--sample", action="append", help="Exact sample label; repeat to select multiple samples.")
    style.add_argument("--width", help="Native line width with unit, such as 0.7pt.")
    style.add_argument("--color", help="Native color, such as #2878B5.")
    style.add_argument("--figure", help="Registered figure identity; otherwise resolve the target's figure.")
    style.add_argument("--task-dir", type=Path)
    style.add_argument("--json", action="store_true")
    style.add_argument("--full", action="store_true", help="Return the detailed task response.")
    for name in ("inspect", "resume"):
        action = actions.add_parser(name)
        action.add_argument("target", type=Path)
        action.add_argument("--json", action="store_true")
        action.add_argument("--full", action="store_true", help="Return the detailed task response; default is a compact receipt.")
        if name == "resume":
            answer = action.add_mutually_exclusive_group(required=True)
            answer.add_argument("--response", type=Path, metavar="JSON_FILE", help="Path to the small source-plan/preview answer JSON file; use the returned response_template.")
            answer.add_argument("--accept-preview", action="store_true", help="Accept the reviewed preview named by --expected-operation-id.")
            answer.add_argument("--retry", action="store_true", help="Retry the existing task after resolving its reported blocker.")
            action.add_argument("--expected-operation-id", help="Required only with --accept-preview; never inferred from task history.")
    group = actions.add_parser("group", help="Run an explicit experiment list and review all native figures together.")
    group_actions = group.add_subparsers(dest="group_action", required=True)
    for name in ("capabilities", "start", "inspect", "resume"):
        action = group_actions.add_parser(name)
        action.add_argument("--json", action="store_true")
        if name == "start":
            action.add_argument("--request", type=Path, required=True)
            action.add_argument("--group-dir", type=Path, required=True)
        elif name in {"inspect", "resume"}:
            action.add_argument("target", type=Path)
            if name == "resume":
                action.add_argument("--responses", type=Path, help="JSON array of item/task-bound answers. Omit to continue pending work.")
    compare = actions.add_parser("compare", help="Compare independent native alternatives from one saved figure, then select one.")
    compare_actions = compare.add_subparsers(dest="compare_action", required=True)
    for name in ("capabilities", "start", "inspect", "resume", "select"):
        action = compare_actions.add_parser(name)
        action.add_argument("--json", action="store_true")
        if name == "start":
            action.add_argument("--request", type=Path, required=True)
            action.add_argument("--comparison-dir", type=Path, required=True)
        elif name != "capabilities":
            action.add_argument("target", type=Path)
            if name == "select":
                action.add_argument("--selection", type=Path, required=True)
    subparsers.add_parser("mcp", help="Run the optional external-AI MCP stdio server.")
