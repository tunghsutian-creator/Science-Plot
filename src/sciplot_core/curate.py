from sciplot_core.semantic_sources.torque_sources import (
    _read_torque_full_series,
    _torque_source_files,
)


def _project_relative(path: Path, project_dir: Path) -> str:
    try:
        return str(path.relative_to(project_dir))
    except ValueError:
        return str(path)


def _prepare_torque_curation(
    project_dir: Path,
    *,
    input_path: Path,
    project_name: str,
) -> dict[str, Any]:
    """Assemble selection before Intake admits its first project generation."""
    curation_dir = project_dir / "curation"
    processed_dir = project_dir / "processed"
    curation_dir.mkdir(parents=True, exist_ok=True)
    processed_dir.mkdir(parents=True, exist_ok=True)

    request_path = project_dir / "plot_request.json"
    request = json.loads(request_path.read_text(encoding="utf-8"))
    source_dir = Path(request["input"])
    if not source_dir.is_absolute():
        source_dir = project_dir / source_dir
    source_files = _torque_source_files(source_dir)
    if not source_files:
        raise ValueError(
            f"No torque files found in prepared project source directory: {source_dir}"
        )

    selection_items: list[dict[str, Any]] = []
    full_series_list = []
    for source_file in source_files:
        full_series = _read_torque_full_series(source_file)
        selection = _auto_torque_event_selection(full_series)
        selection.update(
            {
                "source_path": str(source_file.resolve()),
                "source_name": source_file.name,
            }
        )
        full_series_list.append(full_series)
        selection_items.append(selection)
    plot_labels = _compact_torque_sample_labels(
        [item["sample"] for item in selection_items]
    )
    selected_series = []
    for full_series, selection, plot_label in zip(
        full_series_list, selection_items, plot_labels, strict=False
    ):
        selection["plot_label"] = plot_label
        selected_series.append(_apply_torque_selection(full_series, selection))

    plot_data_path = processed_dir / "torque_curated_plot_data.csv"
    _write_curve_table(selected_series, plot_data_path)
    selection_path = curation_dir / "torque_selection.json"
    plot_request_path = project_dir / "plot_request.json"
    project_slug = project_dir.name
    project_file = project_dir / f"{project_slug}.sciplot.json"

    selection_payload: dict[str, Any] = {
        "kind": "sciplot_torque_curation",
        "version": 1,
        "created_at": utc_now_iso(),
        "project_name": project_name,
        "input_path": str(input_path),
        "mode": "last_batch_event",
        "samples": selection_items,
        "files": {
            "selection": str(selection_path),
            "plot_data": str(plot_data_path),
            "plot_request": str(plot_request_path),
            "project_file": str(project_file),
            "zip": str(project_dir.parent / f"{project_slug}.zip"),
        },
    }
    selection_path.write_text(
        json.dumps(json_safe(selection_payload), indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    request["series_order"] = plot_labels
    render_options = request.get("render_options")
    if not isinstance(render_options, dict):
        render_options = {}
    render_options["series_order"] = plot_labels
    request["render_options"] = render_options
    study_model = request.get("study_model")
    if isinstance(study_model, dict):
        study_model["sample_order"] = plot_labels
        render_defaults = study_model.get("render_defaults")
        if not isinstance(render_defaults, dict):
            render_defaults = {}
        render_defaults["series_order"] = plot_labels
        study_model["render_defaults"] = render_defaults
    request.update(
        {
            "recipe": "auto",
            "rule_id": "torque_curve",
            "curation": _project_relative(selection_path, project_dir),
            "review_notes": ["Generated by SciPlot torque curation."],
        }
    )
    plot_request_path.write_text(
        json.dumps(json_safe(request), indent=2, ensure_ascii=False), encoding="utf-8"
    )

    return selection_payload


def curate_torque_project(
    input_path: str | Path,
    *,
    output_root: Path,
    project_name: str | None = None,
) -> dict[str, Any]:
    input_path = Path(input_path).expanduser().resolve()
    output_root = output_root.expanduser().resolve()
    session = prepare_intake_session(input_path, output_root=output_root)
    if session.get("rule_id") != "torque_curve":
        raise ValueError(
            f"Expected torque data, but detected `{session.get('rule_id')}`."
        )
    if project_name:
        session["project_name"] = project_name
    selection_payload: dict[str, Any] | None = None
    preparation_error: Exception | None = None

    def prepare(project_dir: Path) -> dict[str, Any]:
        nonlocal selection_payload, preparation_error
        try:
            selection_payload = _prepare_torque_curation(
                project_dir,
                input_path=input_path,
                project_name=str(session["project_name"]),
            )
            from sciplot_core.studio import prepare_studio_document

            return prepare_studio_document(project_dir, _new_creation=True)
        except Exception as exc:
            # Intake preserves a blocked creation receipt. This route used to
            # propagate its final preparation failure, so keep that exact cause
            # after the existing factory records the failure; never report ready.
            preparation_error = exc
            raise

    project = create_intake_project_from_session(
        session, project_factory=partial(create_intake_project, studio_preparer=prepare)
    )
    if preparation_error is not None:
        raise preparation_error
    assert selection_payload is not None
    project_dir = Path(project["project_dir"])
    files = selection_payload["files"]
    with edit_intake_project_manifest(
        project_dir, mirror_path=Path(files["project_file"]), require_existing=True
    ) as manifest:
        assert manifest is not None
        manifest["kind"] = "sciplot_torque_curation_project"
        manifest["curation"] = {
            "mode": "last_batch_event",
            "selection_path": files["selection"],
            "plot_data_path": files["plot_data"],
            "samples": selection_payload["samples"],
        }
        manifest["files"] = {
            "project_dir": str(project_dir),
            "plot_request": files["plot_request"],
            "project_file": files["project_file"],
            "selection": files["selection"],
            "plot_data": files["plot_data"],
        }
    zip_path = refresh_intake_project_zip(project_dir)
    return {
        "kind": "sciplot_torque_curation_project",
        "project_name": selection_payload["project_name"],
        "project_dir": str(project_dir),
        "plot_request": files["plot_request"],
        "selection_path": files["selection"],
        "plot_data_path": files["plot_data"],
        "project_file": files["project_file"],
        "zip_path": str(zip_path),
        "samples": selection_payload["samples"],
    }


__all__ = ["curate_torque_project"]
